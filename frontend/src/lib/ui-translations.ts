const languages: readonly Language[] = ['en', 'th', 'zh-CN', 'ja'];
const dictionary = new Map<string, readonly string[]>();
for (const row of rows) {
  dictionary.set(row[0].trim(), row);
}
// Recognize previously displayed messages too, so changing language also updates
// an existing toast/error instead of leaving it in the previous language.
for (const row of rows) for (const translated of row.slice(1)) {
  if (!dictionary.has(translated.trim())) dictionary.set(translated.trim(), row);
}

export function translateUi(source: string, language: Language, values?: Record<string, string | number>): string {
  const key = source.trim();
  const row = dictionary.get(key);
  if (!row) {
    const status = /^Backend request failed \((\d+)\)$/.exec(key);
    if (status) return translateUi('Backend request failed ({status})', language, { status: status[1] });
    // Nest validation responses can contain several independent messages.
    if (source.includes(', ') && !values) return source.split(', ').map(part => translateUi(part, language)).join(', ');
  }
  const result = row ? source.slice(0, source.indexOf(key)) + row[languages.indexOf(language)] + source.slice(source.indexOf(key) + key.length) : source;
  return values ? result.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match)) : result;
}

export function useUiTranslation() {
  const [language] = useAppLanguage();
  return useCallback((source: string, values?: Record<string, string | number>) => translateUi(source, language, values), [language]);
}
